import io
import sys


def rd(p):
    return io.open(p, encoding="utf-8").read()


def ap(p, text, marker):
    s = rd(p)
    if marker in s:
        print("SKIP_EXISTS " + p)
        return
    io.open(p, "w", encoding="utf-8", newline="").write(s.rstrip("\n") + "\n" + text)
    print("APPENDED " + p)


KS = """
## 9. Полная рандомизация v6-провода (v9–v11, 2026-09-04)

### 9.1 Задача

Каждая датаграмма клиент -> нода уходит со **случайного источника** на **случайный
адрес** из routed-пула ноды `2001:db8:2::/48`. Статичный v4-провод — только
аварийный откат.

### 9.2 Флаги

| Флаг | Смысл |
|------|--------|
| `-peerpool6 CIDR` | пул ЦЕЛЕЙ на ноде (anyip, весь /48 маршрутизует брокер) |
| `-wire6src auto|CIDR` | пул ИСТОЧНИКОВ: `auto` — нативный префикс провайдера |
| `-wire6srcn N` | сколько источников держать одновременно (1..64, дефолт 16) |
| `-wire6rot сек` | переезд набора источников и исходного порта |

### 9.3 Механика

- `srcPool6` (`wiresrc6.go`) держит N сокетов, каждый прибит к своему адресу;
  источник выбирается на каждый пакет (`pick`), набор переезжает по `refreshLoop`
  с `srcGrace = 5s` на доживание ответов на старые адреса.
- Linux — `IPV6_FREEBIND` (per-socket, `net.ipv6.ip_nonlocal_bind` на ноде остаётся `0`).
  Windows — адреса добавляются через PowerShell + ожидание DAD.
- Цель — `nextDst` на каждый пакет (доказано стендом: 22 датаграммы — 22 уникальные цели).
- Откат по ПРИЁМУ, а не по ошибкам отправки: `wire6SilenceSec = 12`,
  `wire6MinSentToTrip = 20`, `wire6RetryDownSec = 60`, `wireFailsToFallback = 5`.
- Поле лога `провод=` показывает факт: `v6/источников:N` | `v6` | `v4-откат`.

### 9.4 FAIL-CLOSED (v11) — главный урок поля

v6-провод поднимается только при двух условиях ОДНОВРЕМЕННО:

1. `srcReady` — есть нативный глобальный v6-адрес для источника;
2. `pinned` — `rot.PinWirePool()` вернул `nil`, т.е. пул доказанно уведён МИМО туннеля.

Иначе — `wire6: FAIL-CLOSED: ...` и честная работа по v4-проводу. Петлестоп
`loopGuardDrop()` имеет два плеча: v4-dst == проводной IP ноды (байты 16..20) и
**v6-dst внутри пула провода** (байты 24..40); работает даже когда провод выключен
(`wirePool6` парсится всегда). Тест — `TestLoopGuardDrop`.

### 9.5 Уроки полевых прогонов (Windows, LAPTOP-4LN8TLJH)

| Время | Симптом | Причина | Лечение |
|-------|---------|---------|----------|
| 13:5x | `'или' is not recognized...` | cmd.exe ломается на UTF-8-кириллице в `.bat` | BAT только ASCII (v10) |
| 14:08 | `New-NetRoute ... Error 87` | хвост маршрута от прошлого запуска | идемпотентный `PinWirePool` (v10) |
| 14:08 | `wire6src: exit status 4` | узкий фильтр `PrefixOrigin` | расширенный `Detect` + дамп (v10) |
| 14:22 | `tunRd` 23k за 3с, `loop=0`, адаптер проседает | pin упал (exit 3) + туннельный `::/0` -> датаграммы провода в свой же TUN, петля усиления; петлестоп был только v4-вый | FAIL-CLOSED + v6-плечо петлестопа (v11) |

Физическая граница, установленная полем: у клиентской машины **нет ни одного
глобального IPv6-адреса** (роутер даёт `::/0` через `fe80::1`, но не даёт
префикс). Доказательства: пустой `addr`-дамп `Detect` и 54k пакетов Wireshark,
где весь v6 — только link-local. Значит случайный ИСХОДНЫЙ v6 с этого ПК
невозможен в принципе — нужен v6 от провайдера, 6in4 на самом клиенте либо
рандомизация на плече нода <-> выход.

### 9.6 Ограничение энтропии (говорить вслух)

Цель — случайная на КАЖДЫЙ пакет. Источник — случайный из N адресов набора
(дефолт 16), набор целиком переезжает каждые `-wire6rot` секунд, а не 2^64 на
пакет: `IPV6_PKTINFO` на отправке не реализован на windows/amd64.

### 9.7 Стенд

`.tools/ks/ks_v6src_test.sh` (netns SA/SB, `POOL=fd6c:2a03:5b4a::/48`,
`SRC=fd6c:2a03:5b49:1::/64`). Гейты: уникальных целей == число датаграмм,
адресов вне префиксов == 0, `udpRecv`/`tunWr` растут, обрыв v6 -> откат на v4,
туннель жив. Маркер успеха — `KS_V6SRC_TEST_DONE`.
"""

