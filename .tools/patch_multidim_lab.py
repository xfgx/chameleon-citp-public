'// наблюдаемых осей преимущество атакующему (delay-embedding). Мутация (T) — главная',
'// защита; проверяем, что она держится и при K каналах.',
'',
'func cmdMultidim(args []string) {',
T + 'fs := flag.NewFlagSet("multidim", flag.ExitOnError)',
T + 'windows := fs.Int("windows", 3000, "окон измерения BER на канал")',
T + 'syncMax := fs.Int("syncmax", 40000, "макс. сэмплов на захват sync")',
T + '_ = fs.Parse(args)',
T + 'S := 32',
T + 'c := chaossync.MustDecimal("0.85")',
T + 'delta := chaossync.FromRaw(int64(1) << 40) // 2^-8 — дефолтная амплитуда модуляции',
T + 'syncThresh := chaossync.MustDecimal("0.00005")',
T + 'mod := chaossync.Modulator{Delta: delta, S: S}',
T + 'fmt.Println("# Рычаг 1: K параллельных осей в одном хаос-потоке (идеальный канал, loopback)")',
T + 'fmt.Println("K,sync_samples,ber_min,ber_mean,ber_max,recon_stat,recon_mut")',
T + 'for _, K := range []int{1, 2, 3, 4} {',
T + T + 'epoch := uint64(4242)',
T + T + 'field := chaossync.DeriveField(labMaster, epoch)',
T + T + 'drives := chaossync.DeriveDrives(field, K)',
'',
T + T + '// (а) время захвата sync: связь на K сайтов из чужого состояния, без модуляции.',
T + T + 'syncSamples := -1',
T + T + '{',
T + T + T + 'txX := chaossync.EpochInit(labMaster, epoch)',
T + T + T + 'rxX := chaossync.EpochInit(labMaster, epoch+31337)',
T + T + T + 'for i := 0; i < *syncMax; i++ {',
T + T + T + T + 'field.Step(&txX)',
T + T + T + T + 'y := make([]chaossync.Fxp, K)',
T + T + T + T + 'for ch := 0; ch < K; ch++ {',
