T + T + T + T + T + '}',
T + T + T + T + '}',
T + T + T + T + 'if maxAbs < syncThresh {',
T + T + T + T + T + 'syncSamples = i',
T + T + T + T + T + 'break',
T + T + T + T + '}',
T + T + T + '}',
T + T + '}',
'',
T + T + '// (б) per-channel BER: K независимых битовых потоков после прогрева.',
T + T + 'ber := make([]float64, K)',
T + T + '{',
T + T + T + 'txX := chaossync.EpochInit(labMaster, epoch)',
T + T + T + 'rxX := chaossync.EpochInit(labMaster, epoch)',
