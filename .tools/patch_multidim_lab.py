T + T + T + T + '}',
T + T + T + T + 'r := field.ObserverStepMulti(&rxX, y, c, drives)',
T + T + T + T + 'maxAbs := chaossync.Fxp(0)',
T + T + T + T + 'for ch := 0; ch < K; ch++ {',
T + T + T + T + T + 'if r[ch].Abs() > maxAbs {',
