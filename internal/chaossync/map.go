package chaossync

// map.go — гиперхаотическое ядро: одномерная сеть связанных логистических
// отображений (coupled map lattice, CML) над Q16.48.
//
// Свободная динамика (передатчик):
//
//	f(x) = μ_i · x · (1 − x)
//	x_i' = (1 − ε1 − ε2) · f(x_i) + ε1 · f(x_prev(i)) + ε2 · f(x_next(i))
//
// В гладкой модели при μ ∈ [3.9,4), ε1,ε2 ≥ 0 и ε1+ε2 ≤ 1 куб [0,1]^8
// инвариантен как выпуклая комбинация f ∈ [0,1]. Эти диапазоны сами по себе
// НЕ гарантируют положительных показателей Ляпунова или гиперхаоса.
// Для Q16.48 отдельно учитываются округление и конечность пространства состояний.
//
// Наблюдатель Pecora–Carroll (приёмник) — ObserverStep: свободный шаг +
// коррекция драйв-сайта скалярным сигналом с коэффициентом связи c.

// Sites — размерность решётки (число сайтов CML).
const Sites = 8

// MaxChan — максимум параллельных каналов многомерного кодирования
// (Рычаг 1: гиперхаос, несколько синхронизирующихся подпространств).
const MaxChan = 4

// FieldParams — параметры векторного поля f_k одной эпохи.
// Вся эпоха выводится из мастер-ключа (schedule.go); на провод не уходит.
type FieldParams struct {
	Mu    [Sites]Fxp // логистический параметр каждого сайта, [3.9, 4.0)
	Eps1  Fxp        // связь с prev-соседом; диапазон зависит от класса (schedule.go)
	Eps2  Fxp        // связь с next-соседом; диапазон зависит от класса (schedule.go)
	Next  [Sites]int // топология: гамильтонов цикл по сайтам
	Prev  [Sites]int
	Drive int // индекс сайта-источника скалярного сигнала h(x) = x[Drive]
}

// Step — один шаг свободной динамики: x ← F_k(x). Чистая функция состояния.
func (p *FieldParams) Step(x *[Sites]Fxp) {
	var f [Sites]Fxp
	for i := 0; i < Sites; i++ {
		xi := x[i]
		f[i] = p.Mu[i].Mul(xi).Mul(One.Sub(xi))
	}
	var nx [Sites]Fxp
	for i := 0; i < Sites; i++ {
		fi := f[i]
		nx[i] = fi.
			Add(p.Eps1.Mul(f[p.Prev[i]].Sub(fi))).
			Add(p.Eps2.Mul(f[p.Next[i]].Sub(fi)))
	}
	*x = nx
}

// ObserverStep — шаг наблюдателя: свободный шаг, затем коррекция
// драйв-сайта по скалярному сигналу y с коэффициентом c ∈ [0,1]:
//
//	x[Drive] ← F_d(x) + c · (y − F_d(x))
//
// Возвращает ошибку синхронизации (residual) r = y − F_d(x) ДО коррекции —
// именно из её динамики приёмник декодирует данные (modem.go) и судит о
// синхронизме. При c = 1 драйв-сайт жёстко подменяется сигналом
// (классическая схема Pecora–Carroll); c ∈ [0.8, 0.95) фильтрует шум
// квантования/канала ценой более медленной подтяжки.
func (p *FieldParams) ObserverStep(x *[Sites]Fxp, y Fxp, c Fxp) Fxp {
	p.Step(x)
	pred := x[p.Drive]
	r := y.Sub(pred)
	x[p.Drive] = pred.Add(c.Mul(r))
	return r
}

// ObserverStepMulti — многоканальный шаг наблюдателя (Рычаг 1). Свободный шаг,
// затем коррекция каждого из K драйв-сайтов своим скалярным сигналом. Возвращает
// per-channel residual'ы r[ch] = y[ch] − F(x)[drives[ch]] ДО коррекции — из их
// динамики декодируется K независимых битовых потоков в одном хаос-сигнале.
// Число каналов само по себе не гарантирует синхронизацию: важны выбор
// координат, расписание, старшая условная оценка и фактическая ошибка.
// Отрицательной суммы оценок недостаточно. См. docs/KS-RESEARCH.md и
// TestKSResearchScheduleRegression; лабораторные результаты не доказывают
// устойчивость к реальному каналу или скрытность KS-трафика.
func (p *FieldParams) ObserverStepMulti(x *[Sites]Fxp, y []Fxp, c Fxp, drives []int) [MaxChan]Fxp {
	p.Step(x)
	var r [MaxChan]Fxp
	for ch := 0; ch < len(drives) && ch < MaxChan; ch++ {
		d := drives[ch]
		pred := x[d]
		r[ch] = y[ch].Sub(pred)
		x[d] = pred.Add(c.Mul(r[ch]))
	}
	return r
}
