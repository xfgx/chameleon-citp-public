package chameleon

// Profile — "личность" сеанса: параметры маскировки, выведенные из seed.
// Каждый новый сеанс получает другой профиль, поэтому сигнатуру протокола
// составить невозможно: заголовки, длины паддинга и "характер" фреймов
// меняются от подключения к подключению.
type Profile struct {
	MinHeader int // минимальная длина мусорного заголовка перед фреймом
	HeaderVar int // разброс длины заголовка
	MaxPad    int // максимальная длина хвостового паддинга
	Flavor    int // "вкус" сеанса — зарезервировано под имитацию паттернов
	// (Instagram-like чередование размеров, видео-чанки и т.п.)
}

// NewProfile выводит профиль из отдельного DRBG-потока "profile".
func NewProfile(seed []byte) *Profile {
	d := NewDRBG(seed, "profile")
	return &Profile{
		MinHeader: 4 + d.Intn(9),  // 4..12 байт мусорного заголовка
		HeaderVar: 1 + d.Intn(12), // +0..12 случайных байт
		MaxPad:    d.Intn(256),    // 0..255 байт паддинга в хвосте
		Flavor:    d.Intn(4),      // 4 базовых характера трафика
	}
}
